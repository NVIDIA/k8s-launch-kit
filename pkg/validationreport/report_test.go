package validationreport_test

import (
	"bytes"
	"embed"
	"html"
	"strings"
	"testing"
	"time"

	"github.com/nvidia/k8s-launch-kit/pkg/validationreport"
	. "github.com/onsi/ginkgo/v2"
	. "github.com/onsi/gomega"
)

//go:embed testdata/body.html.tmpl
var targetTemplate embed.FS

func TestValidationReport(t *testing.T) {
	RegisterFailHandler(Fail)
	RunSpecs(t, "Validation report")
}

var _ = Describe("Validation report shell", func() {
	It("renders a target's typed body and escapes page and body text", func() {
		const markup = `</title><script>alert("canary")</script>`
		page := validationreport.Page{
			Title:       markup,
			Heading:     "Target validation",
			GeneratedAt: time.Date(2026, 11, 19, 13, 0, 0, 0, time.FixedZone("CET", 3600)),
			Version:     markup,
			Metadata:    []validationreport.Field{{Label: "Target", Value: markup}},
			Outcome: validationreport.OutcomeView{
				Label:   "INCOMPLETE",
				Style:   validationreport.OutcomeWarning,
				Reasons: []string{markup},
				Notes:   []string{markup},
			},
		}
		type targetBody struct {
			Observation string
		}
		tmpl, err := validationreport.NewTemplate(targetTemplate, "testdata/body.html.tmpl", nil)
		Expect(err).NotTo(HaveOccurred())
		var out bytes.Buffer
		Expect(tmpl.Execute(&out, validationreport.View[targetBody]{
			Page: page,
			Body: targetBody{Observation: markup},
		})).To(Succeed())

		rendered := out.String()
		escaped := html.EscapeString(markup)
		Expect(rendered).To(ContainSubstring("<title>" + escaped + "</title>"))
		Expect(rendered).To(ContainSubstring("<h1>Target validation</h1>"))
		Expect(rendered).To(ContainSubstring("<dt>Target</dt> <dd>" + escaped + "</dd>"))
		Expect(rendered).To(ContainSubstring("class=\"verdict-banner verdict-warning\""))
		Expect(rendered).To(ContainSubstring("INCOMPLETE"))
		Expect(rendered).To(ContainSubstring("<section><h2>Target evidence</h2><p>" + escaped + "</p></section>"))
		Expect(rendered).To(ContainSubstring("Generated by <strong>NVIDIA Kubernetes Launch Kit</strong> · " + escaped + " · 2026-11-19 12:00:00 UTC"))
		Expect(rendered).NotTo(ContainSubstring("<script>"))
		Expect(strings.Count(rendered, "<li>"+escaped+"</li>")).To(Equal(2))
	})
})
