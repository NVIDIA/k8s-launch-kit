"""Render repository-owned OpenSpec procedure metadata; never execute commands."""

import argparse
import html
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "openspec/workflows/dpf-discovery.json"
OUTPUT = ROOT / "docs/user/dpf-workflows.md"
ID = re.compile(r"^[a-z][a-z0-9-]*$")


def text(value, where):
    if not isinstance(value, str) or not value.strip():
        raise ValueError(f"{where} must be nonempty text")


def keys(value, required, optional, where):
    if not isinstance(value, dict):
        raise ValueError(f"{where} must be an object")
    if set(value) - required - optional or required - set(value):
        raise ValueError(f"{where} has unknown or missing fields")


def validate(doc):
    keys(doc, {"formatVersion", "title", "introduction", "workflows"}, {"$comment"}, "document")
    if type(doc["formatVersion"]) is not int or doc["formatVersion"] != 1:
        raise ValueError("unsupported formatVersion")
    text(doc["title"], "title")
    text(doc["introduction"], "introduction")
    if not isinstance(doc["workflows"], list) or not doc["workflows"]:
        raise ValueError("workflows must be a nonempty list")
    workflow_ids = set()
    for workflow in doc["workflows"]:
        keys(workflow, {"id", "title", "introduction", "steps"}, set(), "workflow")
        identifier = workflow["id"]
        if not isinstance(identifier, str) or not ID.fullmatch(identifier) or identifier in workflow_ids:
            raise ValueError("invalid or duplicate workflow ID")
        workflow_ids.add(identifier)
        text(workflow["title"], "workflow title")
        text(workflow["introduction"], "workflow introduction")
        if not isinstance(workflow["steps"], list) or not workflow["steps"]:
            raise ValueError("steps must be a nonempty list")
        step_ids = set()
        for step in workflow["steps"]:
            keys(step, {"id", "title", "body", "transitions"}, set(), "step")
            identifier = step["id"]
            if not isinstance(identifier, str) or not ID.fullmatch(identifier) or identifier in step_ids:
                raise ValueError("invalid or duplicate step ID")
            step_ids.add(identifier)
            text(step["title"], "step title")
            text(step["body"], "step body")
            if not isinstance(step["transitions"], list):
                raise ValueError("transitions must be a list")
        for step in workflow["steps"]:
            destinations = set()
            for transition in step["transitions"]:
                keys(transition, {"to", "label"}, set(), "transition")
                if not isinstance(transition["to"], str) or transition["to"] not in step_ids:
                    raise ValueError("transition points to an unknown step")
                text(transition["label"], "transition label")
                if transition["to"] in destinations:
                    raise ValueError("duplicate transition destination")
                destinations.add(transition["to"])


def diagram_text(value):
    # Titles/labels are data, not Mermaid markup. In particular, newlines and
    # quotes cannot terminate a diagram node or inject another graph statement.
    return html.escape(" ".join(value.split()), quote=True)


def render(doc):
    validate(doc)
    lines = ["<!--", "Copyright 2026 NVIDIA CORPORATION & AFFILIATES",
             "SPDX-License-Identifier: Apache-2.0", "",
             "Generated by scripts/generate-workflow-docs.py from",
             "openspec/workflows/dpf-discovery.json. Edit the source, then regenerate.",
             "-->", "", f"# {doc['title']}", "", doc["introduction"].strip(), ""]
    for workflow in doc["workflows"]:
        lines += [f"## {workflow['title']} {{#{workflow['id']}}}", "",
                  workflow["introduction"].strip(), "", "```mermaid", "flowchart TD"]
        # Sequential node identifiers avoid Mermaid keyword collisions (e.g. end).
        nodes = {step["id"]: f"n{i}" for i, step in enumerate(workflow["steps"], 1)}
        for step in workflow["steps"]:
            lines.append(f'  {nodes[step["id"]]}["{diagram_text(step["title"])}"]')
        for step in workflow["steps"]:
            for transition in step["transitions"]:
                lines.append(f'  {nodes[step["id"]]} -->|"{diagram_text(transition["label"])}"| {nodes[transition["to"]]}')
        lines += ["```", ""]
        for number, step in enumerate(workflow["steps"], 1):
            lines += [f"### {number}. {step['title']} {{#{workflow['id']}-{step['id']}}}",
                      "", step["body"].strip(), ""]
            if step["transitions"]:
                links = [f"[{t['label']}](#{workflow['id']}-{t['to']})" for t in step["transitions"]]
                lines += ["Next: " + "; ".join(links) + ".", ""]
    return "\n".join(lines)


def unique_keys(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f"duplicate JSON field: {key}")
        result[key] = value
    return result


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail on drift without writing output")
    parser.add_argument("--source", type=Path, default=SOURCE)
    parser.add_argument("--output", type=Path, default=OUTPUT)
    args = parser.parse_args(argv)
    try:
        content = render(json.loads(args.source.read_text(encoding="utf-8"), object_pairs_hook=unique_keys))
        if args.check:
            if not args.output.is_file() or args.output.read_text(encoding="utf-8") != content:
                raise ValueError("workflow documentation is missing or stale; run scripts/generate-workflow-docs.py")
        else:
            args.output.write_text(content, encoding="utf-8")
    except (OSError, ValueError) as error:
        print(f"Workflow documentation: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
